import { _electron as electron } from '@playwright/test';
import path from 'node:path';
import fs from 'node:fs';
const apiKey = process.env.PAPER_TEST_KEY;
if (!apiKey) throw new Error('API key is required in the test process environment');
const root = path.resolve('.');
const sample = process.env.TEST_PDF || path.join(root, 'test-assets', 'attention-is-all-you-need.pdf');
const profile = process.env.TEST_PROFILE || path.join(root, 'test-assets', '.papertutor-profile');
fs.mkdirSync(path.join(root, 'screenshots'), { recursive: true });
let app = await electron.launch({ args: ['.', `--user-data-dir=${profile}`, `--test-pdf=${sample}`], cwd: root });
let page = await app.firstWindow();
await page.getByRole('button', { name: 'PT PaperTutor' }).waitFor();
await page.getByLabel('设置').click();
await page.getByLabel('API Key').fill(apiKey);
await page.getByLabel('Model').fill('deepseek-flash');
await page.getByLabel('Max Tokens').fill('600');
await page.getByLabel('启用流式输出').uncheck();
await page.getByText('测试连接').click();
await page.getByText('连接成功，模型可以正常调用。').waitFor({ timeout: 120000 });
await page.getByText('保存设置').click();
await page.getByRole('heading', { name: 'AI 模型' }).waitFor({ state: 'hidden' });
await page.getByText('导入论文', { exact: true }).click();
await Promise.race([page.getByText('Paper Overview').waitFor({ timeout: 180000 }), page.locator('.global-error').waitFor({ timeout: 180000 })]);
if (await page.locator('.global-error').count()) throw new Error(`Pre-reading failed: ${await page.locator('.global-error').innerText()}`);
await page.screenshot({ path: path.join(root, 'screenshots', 'overview-live.png') });
await page.getByText('返回阅读').click();
await page.locator('.page-wrap').waitFor({ timeout: 30000 });
await page.locator('.text-layer span').first().waitFor({ timeout: 30000 });
await page.getByLabel('当前页').fill(process.env.TEST_PAGE || '3');
await page.waitForFunction(() => document.querySelectorAll('.text-layer span').length > 20, null, { timeout: 30000 });
await page.evaluate(() => { const spans = [...document.querySelectorAll('.text-layer span')].filter(x => (x.textContent || '').trim().length > 8).slice(8, 15); if (!spans.length) throw new Error('No selectable PDF text'); const range = document.createRange(); range.setStart(spans[0].firstChild, 0); const last = spans.at(-1); range.setEnd(last.firstChild, last.textContent.length); const sel = getSelection(); sel.removeAllRanges(); sel.addRange(range); spans[0].parentElement.dispatchEvent(new MouseEvent('mouseup', { bubbles: true })); });
await Promise.race([page.locator('.turn.assistant').last().waitFor({ timeout: 180000 }), page.locator('.ai-error').waitFor({ timeout: 180000 })]);
if (await page.locator('.ai-error').count()) throw new Error(`Explanation failed: ${await page.locator('.ai-error').innerText()}`);
await page.screenshot({ path: path.join(root, 'screenshots', 'ai-answer-live.png') });
const selected = await page.locator('.selection blockquote').innerText(); const answer = await page.locator('.turn.assistant').last().innerText();
if (selected.length < 10 || !answer.includes('导师阅读建议')) throw new Error('Grounded answer did not meet acceptance shape');
await page.getByLabel('下一页').click(); await page.getByLabel('放大').click(); await page.locator('.pdf-scroll').evaluate(e => e.scrollTop = 120);
await page.setViewportSize({ width: 800, height: 600 }); await page.screenshot({ path: path.join(root, 'screenshots', '800x600-live.png') }); await page.setViewportSize({ width: 1920, height: 1080 }); await app.close();
app = await electron.launch({ args: ['.', `--user-data-dir=${profile}`], cwd: root }); page = await app.firstWindow(); await page.locator('.page-wrap').waitFor({ timeout: 30000 }); const current = await page.getByLabel('当前页').inputValue(); if (Number(current) < 2) throw new Error('Reading position was not restored'); await app.close();
console.log(JSON.stringify({ connection: 'passed', preReading: 'passed', selectionLength: selected.length, groundedAnswer: 'passed', restart: 'passed', restoredPage: current }));
